"""Draw the repository banner (docs/assets/banner.svg) and the CorpSEC mark (logo.svg).

The mark is the app's inspection seal (apps/web/src/components/GradeSeal.tsx) with "A+".
Ring letters are placed one by one instead of with <textPath>, so every SVG renderer
draws them. See README.md in this folder for turning the SVGs into PNGs.
"""

from __future__ import annotations

import math
from pathlib import Path

HERE = Path(__file__).parent
W, H = 1280, 640
CX, CY = 640, 262
SEAL_R = 118

DISPLAY = 'font-family="Fraunces, serif" font-weight="700"'
SANS = "font-family=\"'Public Sans', sans-serif\""
TEAL, INK, SOFT, NIGHT = "#6fc2ad", "#eee8dc", "#b5bccb", "#0c1320"
# Grade colours of the dark theme (apps/web/src/app/globals.css), as findings on the rings.
MARKS = [(200, -32, "#7fd3a4"), (260, 208, "#f0d36b"), (330, -150, "#7fd3a4"),
         (260, 24, "#ffb870"), (410, -62, "#ff9c94"), (200, 150, "#7fd3a4"),
         (410, 26, "#9cc2f0")]  # fmt: skip

# Public Sans Bold advance widths (em) for the ring text.
_ADVANCE = {"·": 0.26, " ": 0.23, "I": 0.31, "W": 0.97, "M": 0.92, "L": 0.58}


def ring_text(text: str, cx: float, cy: float, r: float, *, top: bool, size: float,
              spacing: float, color: str) -> str:  # fmt: skip
    """Letters along a circle: over the top reading clockwise, or along the bottom upright."""
    widths = [(_ADVANCE.get(ch, 0.7) * size + spacing) for ch in text]
    total = sum(widths) / r  # radians
    angle = (-math.pi / 2 - total / 2) if top else (math.pi / 2 + total / 2)
    out = []
    for ch, w in zip(text, widths, strict=True):
        step = w / r
        mid = angle + step / 2 if top else angle - step / 2
        x, y = cx + r * math.cos(mid), cy + r * math.sin(mid)
        rot = math.degrees(mid) + (90 if top else -90)
        if ch.strip():
            out.append(
                f'<text x="{x:.2f}" y="{y:.2f}" transform="rotate({rot:.2f} {x:.2f} {y:.2f})" '
                f'text-anchor="middle" {SANS} font-weight="700" font-size="{size}" '
                f'fill="{color}">{ch}</text>'
            )
        angle = angle + step if top else angle - step
    return "".join(out)


def seal(cx: float, cy: float, r: float, color: str, backdrop: str | None) -> str:
    parts = []
    if backdrop:
        parts.append(
            f'<circle cx="{cx}" cy="{cy}" r="{r + 14}" fill="{backdrop}" fill-opacity="0.88"/>'
        )
    parts += [
        f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="{color}" stroke-width="{r / 30:.1f}"/>',
        f'<circle cx="{cx}" cy="{cy}" r="{r * 0.905:.1f}" fill="none" stroke="{color}" '
        f'stroke-width="{r / 85:.1f}" stroke-dasharray="{r / 60:.1f} {r / 24:.1f}"/>',
        f'<circle cx="{cx}" cy="{cy}" r="{r * 0.66:.1f}" fill="none" stroke="{color}" stroke-width="{r / 60:.1f}"/>',
        # glyphs sit outward from the baseline on top, inward on the bottom
        ring_text("CORPSEC · SECURITY", cx, cy, r * 0.775, top=True, size=r * 0.127,
                  spacing=r * 0.042, color=color),
        ring_text("WEB · EMAIL · DOMAIN", cx, cy, r * 0.87, top=False, size=r * 0.127,
                  spacing=r * 0.034, color=color),
        f'<text x="{cx}" y="{cy + r * 0.26:.1f}" text-anchor="middle" {DISPLAY} '
        f'font-size="{r * 0.74:.1f}" fill="{color}">A+</text>',
    ]  # fmt: skip
    return "\n  ".join(parts)


def banner() -> str:
    rings = []
    for i, r in enumerate([150, 200, 260, 330, 410, 500]):
        dash = "" if i % 2 == 0 else ' stroke-dasharray="2 7"'
        rings.append(
            f'<circle cx="{CX}" cy="{CY}" r="{r}" fill="none" stroke="{TEAL}" '
            f'stroke-opacity="{0.32 - i * 0.045:.2f}" stroke-width="1.2"{dash}/>'
        )
    marks = []
    for r, deg, col in MARKS:
        a = math.radians(deg)
        x, y = CX + r * math.cos(a), CY + r * math.sin(a)
        marks.append(
            f'<circle cx="{x:.1f}" cy="{y:.1f}" r="9" fill="{col}" fill-opacity="0.16"/>'
            f'<circle cx="{x:.1f}" cy="{y:.1f}" r="3.6" fill="{col}"/>'
        )
    a0, a1, sr = math.radians(-90), math.radians(-40), 520
    sweep = (
        f"M{CX},{CY} L{CX + sr * math.cos(a0):.1f},{CY + sr * math.sin(a0):.1f} "
        f"A{sr},{sr} 0 0 1 {CX + sr * math.cos(a1):.1f},{CY + sr * math.sin(a1):.1f} Z"
    )
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">
  <!-- Generated by make_banner.py. Fonts: Fraunces and Public Sans (SIL OFL 1.1). -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#0c1320"/><stop offset="1" stop-color="#141e30"/>
    </linearGradient>
    <radialGradient id="glow" cx="{CX}" cy="{CY}" r="430" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{TEAL}" stop-opacity="0.30"/>
      <stop offset="0.45" stop-color="{TEAL}" stop-opacity="0.08"/>
      <stop offset="1" stop-color="{TEAL}" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="warm" cx="1180" cy="640" r="520" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#f0a35e" stop-opacity="0.16"/><stop offset="1" stop-color="#f0a35e" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="cool" cx="60" cy="40" r="480" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#5b7fd6" stop-opacity="0.16"/><stop offset="1" stop-color="#5b7fd6" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="sweepFade" cx="{CX}" cy="{CY}" r="{sr}" gradientUnits="userSpaceOnUse">
      <stop offset="0.25" stop-color="{TEAL}" stop-opacity="0.09"/><stop offset="1" stop-color="{TEAL}" stop-opacity="0"/>
    </radialGradient>
    <filter id="soft" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="10"/></filter>
    <pattern id="dots" width="24" height="24" patternUnits="userSpaceOnUse">
      <circle cx="2" cy="2" r="1.1" fill="{INK}" fill-opacity="0.07"/>
    </pattern>
    <radialGradient id="fade" cx="{CX}" cy="{CY}" r="700" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#fff" stop-opacity="1"/><stop offset="1" stop-color="#fff" stop-opacity="0.15"/>
    </radialGradient>
    <mask id="dotmask"><rect width="{W}" height="{H}" fill="url(#fade)"/></mask>
  </defs>
  <rect width="{W}" height="{H}" fill="url(#bg)"/>
  <rect width="{W}" height="{H}" fill="url(#dots)" mask="url(#dotmask)"/>
  <rect width="{W}" height="{H}" fill="url(#cool)"/>
  <rect width="{W}" height="{H}" fill="url(#warm)"/>
  <rect width="{W}" height="{H}" fill="url(#glow)"/>
  <path d="{sweep}" fill="url(#sweepFade)" filter="url(#soft)"/>
  {"".join(rings)}
  {"".join(marks)}
  {seal(CX, CY, SEAL_R, TEAL, NIGHT)}
  <text x="{CX}" y="{CY + 232}" text-anchor="middle" {DISPLAY} font-size="80" fill="{INK}">CorpSEC</text>
  <text x="{CX}" y="{CY + 282}" text-anchor="middle" {SANS} font-weight="500" font-size="25" fill="{SOFT}">Website and email security checks anyone can understand</text>
</svg>
"""


def logo() -> str:
    """The mark alone, square, on a transparent background (teal works on light and dark)."""
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">
  <!-- Generated by make_banner.py. Fonts: Fraunces and Public Sans (SIL OFL 1.1). -->
  {seal(256, 256, 236, "#1d8a74", None)}
</svg>
"""


if __name__ == "__main__":
    (HERE / "banner.svg").write_text(banner(), encoding="utf-8")
    (HERE / "logo.svg").write_text(logo(), encoding="utf-8")
